      SUBROUTINE HSTRY2
C        MODIFIED SLOSH USED FOR EVACUATION STUDY.
      USE PARM2
      INCLUDE 'parm.for'
C
      COMMON /DUMB8/  IP(4),JP(4),IH(4),JH(4)
      COMMON /NFILE/  KNPT,NDATA(3)
      COMMON /STRMSB/ C1,C2,C21,C22,AX,AY,PTENCY,RTENCY
C STIME interferes with C code, so switched to STIME2
      COMMON /STIME2/  ISTM,JHR,ITMADV,NHRAD,IBGNT,ITEND
      COMMON /FRST/   X1(50),X12(50)
      COMMON /DUMY44/ SW(800),CW(800),W1218(2),WMAX(2)
      COMMON /DUMMY4/ S(800),C(800),P(800),DELP(800)
      COMMON /BSN/    PHI,ALTO,ALNO,PHI1,ALT1,ALN1,ALT1C
      COMMON /PIRAD/  PI,RAD
      COMMON /CESAV/  IPN(120),IPL(120),KHSPT
      COMMON /CESAV1/ STATS(120)
      COMMON /GPRT1/  DOLLAR,EBSN
      COMMON /PRHSY/  IPRHR,JUMP,IPRT
      DIMENSION SAVEH(10,12),WIND(10,12),TDIR(10,12)
      CHARACTER*16 STATS
      CHARACTER*2  DOLLAR
      CHARACTER*1 EBSN
      DATA KHR,KHR2/0,0/
C
C
C       KEEP TRACK TIME, ON THE HOUR,HALF HOUR BETWEEN, OR ELSE
C       FROM MOD(IME,100)=1,OR 2,OR 3
C
      GO TO (10,20,30),IPRHR
  10  KHR=KHR+1
      IME=KHR*100+1
      GO TO 40
  20  KHR2=KHR2+1
      IME=KHR2*100+2
      GO TO 40
  30  IME=103
  40  CONTINUE
C      SAVE TIME HISTRIES AT SELECTED GRIDS
C       UPDATED FEB. 1985. SAVE TIME HISTRIES EVERY HALF HOUR.
      IF (IPRHR.EQ.3) RETURN
      LUNIT=NDATA(1)
      DO 195 N=1,KHSPT
      L1=(N-1)*10+1
      L2=L1+9
      DO 190 L=L1,L2
      M=L-L1+1
      I=IPN(L)
      J=IPL(L)
      SAVEH(M,N)=HB(I,J)
C      IF (DOLLAR.EQ.'2$') SAVEH(M,N)=HB(I,J)-ZSUB(J)
 190  CONTINUE
 195  CONTINUE
C        WRITING HISTORICAL SURGES AT SELECTED GRID PTS ONTO TAPE
      WRITE(LUNIT)   IME,((SAVEH(M,N),M=1,10),N=1,KHSPT)
CC      WRITE(*,'(i6,10f6.2)') IME,((SAVEH(M,1),M=1,10),N=1,1)
C
C++++++++COMPUTING VECTOR WIND AT 10 SELECTED POINTS++++++++++++++++++++
C
C
      LUNT=NDATA(2)
      LUNT1=NDATA(3)
      DO 305 N=1,KHSPT
      L1=(N-1)*10+1
      L2=L1+9
      DO 230 L=L1,L2
      M=L-L1+1
      I=IPN(L)
      J=IPL(L)
      X=ELPCL(I)*COSL(J)
      Y=ELPDL(I)*SINL(J)
      XP=X-C1-AX
      YP=Y-C2-AY
      RSQ=XP*XP+YP*YP
      RS=SQRT(RSQ)
      R1=RS/5280.+1.
      K=R1
      R2=K
      DR=R1-R2
      K=MIN0(K,790)
      if (itree(i,j).eq.'2') then
      ncatg=2
      else
      NCATG=1
      endif
      X1218=W1218(NCATG)
      CK1=CW(K)+DR*(CW(K+1)-CW(K))
      SK1=SW(K)+DR*(SW(K+1)-SW(K))
      CCN=X12(15)+RSQ
      CC=1./CCN
      RHOL=ABS(XP*X12(20)+YP*X12(21))
      CCC=CCN*RHOL/(X12(15)+RHOL*RHOL)
      A=RS*X12(9) -X1218*(YP*CK1+XP*SK1)+CCC*X12(23)
      B=RS*X12(10)+X1218*(XP*CK1-YP*SK1)+CCC*X12(24)
      SS=SQRT(A*A+B*B)
      WIND(M,N)=X12(4)*SS*CC*3600./5280.
         IF (SS.LT.1.E-5) THEN
         Z=180.
         ELSE
      Z      =ATAN2(A,B)/1.74532925199433E-2+180.
         ENDIF
  230 TDIR(M,N)=AMOD(Z+PHI,360.)
C++++++++END COMPUTATION OF VECTOR WINDS++++++++++++++++++++++++++++++++
C
 305  CONTINUE
C        WRITING HISTORICAL VECTOR WINDS AT SELECTED POINTS ONTO TAPE
      WRITE(LUNT)   IME,((WIND(M,N),M=1,10),N=1,KHSPT)
      WRITE(LUNT1)  IME,((TDIR(M,N),M=1,10),N=1,KHSPT)
      RETURN
      END
