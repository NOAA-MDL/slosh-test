C       DOCTOR ENTRY PRESSURE FOR LATITUDE OTHER THAN 30 DEG
      PF=.3*(30.-ALTO)*(PDROP/67.7)**2
      KPRES=PDROP+PF+0.5

C       ADDED CHECKS TO MAKE SURE WINDS WERE WITHIN BOUNDS -ARTHUR
      IF (KPRES >= 151) THEN
      KPRES=150
      ENDIF
      IF (KPRES < 1) THEN
      KPRES=1
      ENDIF
C       FINISHED ADDED CHECKS TO MAKE SURE WINDS WERE WITHIN BOUNDS

C       LINEAR SLOPE FORMULA FOR APPROXIMATE MAXIMUM WIND
      VMAX=-WM(KPRES)*RMAX+WB(KPRES)
      VMAX=MAX(VMAX,10.)
      RETURN
      END
