      SUBROUTINE INTWND(PDROP,RMAX,ALTO,VMAX)
C        JELESNIANSKI       AUGUST 1980TDL   IBM 360/195
C
C        PURPOSE
C           THIS SUBROUTINE (INTWND) SETS UP AN INITIAL GUESS FOR THE
C           MAX WIND OF A STATIONARY STORM USING INITIAL INPUT STORM
C           PARAMETERS. THE INITIAL GUESS IS AN ENTRY VALUE TO
C           SUBROUTINE 'FORCE1' FOR ITERATION TO EXACT MAXIMUM WINDS.
C
C        DATA SET USE
C           NONE
C
C        VARIABLES
C             PDROP = PRESSURE DROP FOR 1ST HOUR
C              ALTO = LATITUDE OF BASIN CENTER
C             KPRES = DOCTORED PRESSURE DROP FOR LAT OTHER THAN 30 DEG
C           WM(150) = ARRAY FOR SLOPE OF LINEAR SLOPE FORMULA
C           WB(150) = ARRAY FOR INTERCEPT OF LINEAR SLOPE FORMULA
C              RMAX = RADIUS OF MAXIMUM WIND
C              VMAX = MAXIMUM WIND
C
C        GENERAL COMMENTS
C           THIS SUBROUTINE LIES IN OVERLAY STRMPR. IT IS CALLED IN BY
C           SUBROUTINE 'STRMPR'
C           FOR A GIVEN PRESSURE DROP 'P(100)', THE MAX WIND
C           VARIES ALMOST LINEARLY WITH STORM SIZE 'R(100)'.
C           SEE BELOW;
C
C                              -       E
C                              -      R
C                              -     U
C                              W    S
C                              I   S  WM(KPRES)=SLOPE OF
C                              N  E             PRESSURE
C                              D R              LINE
C                              -P
C           WB(KPRES)=INTERCEPT-
C                              0---R=STORM SIZE----
C
C           THE SLOPE AND INTERCEPT OF THE PRESSURE LINE VARIES
C           WEAKLY WITH LATITUDE OR CORIOLIS. THE GIVEN WM,WB ARE
C           FOR LATITUDE 30 DEG; THE ENTRY PRESSURE AT TIME 'IBGNT'
C           IS DOCTORED TO CORRECT FOR LATITUDE OTHER THAN 30 DEG.
C
