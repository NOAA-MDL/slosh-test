      SUBROUTINE SETCMP_HS(DMCLOCK)
      USE PARM2
      include 'parm.for'
      COMMON /STRMSB/ C1,C2,C21,C22,AX,AY,PTENCY,RTENCY
      COMMON /FFTH/   ITIME,MHALT
      COMMON /STIME2/  ISTM,JHR,ITMADV,NHRAD,IBGNT,ITEND
      COMMON /DUMB3/  IMXB,JMXB,IMXB1,JMXB1
      COMMON /WTEMP/  YDELP,ZDELP,PNN,YC24,ZC24
      COMMON /DUMY44/ SW(800),CW(800),W1218(2),WMAX(2)
      COMMON /TMEREL/ TREAL
      COMMON /FRST/   X1(50),X12(50)
      COMMON /HTNM/ HTMAIN,HTHB,HTUV,HTWV,HTWVT,HTHMX
      character*80 HTMAIN,HTHB,HTUV,HTWV,HTWVT,HTHMX
      REAL DMCLOCK
      CHARACTER(LEN=20)STRING2

      WRITE(STRING2,'("(",I4,"(F9.3,X))")') JMXB1
      OPEN(1001,FILE=HTMAIN,STATUS='OLD')
      OPEN(1004,FILE=HTHMX,STATUS='OLD')
      READ(1001,'(I12)')ITIME
      ITIME=ITIME-1
      READ(1001,'(I12)')ITMADV
      READ(1001,'(I12)')NHRAD
      READ(1001,'(F12.4)')TREAL
      READ(1001,'(F20.4)')DMCLOCK
      READ(1001,'(F15.4)')C1
      READ(1001,'(F15.4)')C2
      READ(1001,'(F15.4)')AX
      READ(1001,'(F15.4)')AY
      READ(1001,'(F15.4)')ZDELP
      READ(1001,'(F15.4)')ZC24
      READ(1001,'(F15.4)')PNN
      READ(1001,'(F15.4)')WMAX(1)
      READ(1001,'(F15.4)')WMAX(2)
      READ(1001,'(F20.4)')X12(4)
      READ(1001,'(F20.4)')X12(7)
      READ(1001,'(F20.4)')X12(9)
      READ(1001,'(F20.4)')X12(10)
      READ(1001,'(F20.4)')X12(11)
      READ(1001,'(F20.4)')X12(12)
      READ(1001,'(F20.4)')X12(15)
      READ(1001,'(F20.4)')X12(17)
      READ(1001,'(F20.4)')X12(20)
      READ(1001,'(F20.4)')X12(21)
      READ(1001,'(F20.4)')X12(23)
      READ(1001,'(F20.4)')X12(24)
      READ(1001,'(F20.4)')X12(49)
      READ(1001,'(F20.4)')X12(50)

C     Water level envelop
      DO I=1,IMXB1
        READ(1004,STRING2)(HMX(I,J),J=1,JMXB1)
      END DO

      CLOSE(1001)
      CLOSE(1004)
      RETURN
      END
