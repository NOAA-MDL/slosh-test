       SUBROUTINE EXTRPT (FLE40)
      COMMON /CESAV/  IPN(120),IPL(120),KHSPT
      COMMON /NFILE/  KNPT,NDATA(3)
      COMMON /CESAV1/ STATS(120)
      COMMON /ARCH/   NOARCH
      CHARACTER*16 STATS
      CHARACTER*1  NOARCH
      CHARACTER*40 FLE40
C
CC      write (*,*)'  name of file 40'
C      READ (*,'(A)') FLE40
      OPEN (40,FILE=FLE40)
      READ (40,20,END=55) KNPT,NOARCH
 20   FORMAT(I3,A1)
C
      IF (KNPT.NE.0) THEN
      KHSPT=1+(KNPT-1)/10
      KHSPT1=KHSPT*10
      READ (40,10)(STATS(I),I=1,KHSPT1)
  10  FORMAT(8A10)
      READ (40,15) (IPN(I),IPL(I),I=1,KHSPT1)
  15  FORMAT(10(I3,I3,2X))
      ENDIF
C
  55  CONTINUE
      CLOSE (40)
       RETURN
      END
